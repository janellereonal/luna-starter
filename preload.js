const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('luna', {
  ask: (text) => ipcRenderer.invoke('ask', text),
  reset: () => ipcRenderer.invoke('reset'),
  setInteractive: (on) => ipcRenderer.send('interactive', on),
  focus: () => ipcRenderer.send('focus'),
  menu: () => ipcRenderer.send('menu'),
  hide: () => ipcRenderer.send('hide'),
  fullscreen: (on) => ipcRenderer.send('fullscreen', on),
  openWindow: () => ipcRenderer.send('chat:window'),
  record: (m) => ipcRenderer.send('chat:record', m),
  history: () => ipcRenderer.invoke('chat:history'),
  onSync: (fn) => ipcRenderer.on('chat:sync', (_e, m) => fn(m)),
  onClear: (fn) => ipcRenderer.on('chat:clear', () => fn()),
  onDelta: (fn) => ipcRenderer.on('delta', (_e, t) => fn(t)),
  onStatus: (fn) => ipcRenderer.on('status', (_e, t) => fn(t)),
  onRoam: (fn) => ipcRenderer.on('roam', (_e, r) => fn(r)),
  onNudge: (fn) => ipcRenderer.on('nudge', (_e, n) => fn(n)),
  onVoice: (fn) => ipcRenderer.on('voice', (_e, v) => fn(v)),
  onSummon: (fn) => ipcRenderer.on('summon', () => fn()),
  onApproval: (fn) => ipcRenderer.on('approval', (_e, a) => fn(a)),
  approve: (id, ok) => ipcRenderer.send('approve', id, ok),
  stop: () => ipcRenderer.invoke('stop'),
  openPath: (p) => ipcRenderer.send('open-path', p),
  openUrl: (u) => ipcRenderer.send('open-url', u),
  openFile: (f) => ipcRenderer.send('open-file', f),
  openSettings: (section) => ipcRenderer.send('open-settings', section),
  config: () => ipcRenderer.invoke('settings:get').then((s) => ({ userName: s.prefs.userName, charName: s.prefs.charName, charIcon: s.prefs.charIcon, tapOpens: s.prefs.tapOpens || 'small' })),
  onConfig: (fn) => ipcRenderer.on('config', (_e, c) => fn(c)),
  onCharacter: (fn) => ipcRenderer.on('character', (_e, c) => fn(c)),
  theme: () => ipcRenderer.invoke('settings:get').then((s) => s.prefs.theme || {}),
  onTheme: (fn) => ipcRenderer.on('theme', (_e, t) => fn(t))
});
